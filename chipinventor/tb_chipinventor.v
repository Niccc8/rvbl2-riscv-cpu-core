//  SCOPE: $dumpvars(2, dut) records the 20 canvas instances and their
//  internals, and nothing else. Dumping all of testbench instead would add
//  the reference-model functions and the SUITE 0 unit DUTs, which is 723
//  signals rather than 248 and makes the platform signal picker unusable.
//  dut.clk_i and dut.rst_i stand in for the testbench clock and reset.
