// CRC-16/CCITT-FALSE: poly 0x1021, MSB-first, no reflection, no final XOR.
// Operand roles match the block: seed is rs1[15:0], data is rs2.
function [15:0] ref_crc;
    input [2:0]  f3;
    input [15:0] seed;
    input [31:0] data;
    reg   [15:0] c;
    reg          fb;
    integer      nbits, bi;
    begin
        c = seed;
        case (f3[1:0])
            2'b00:   nbits = 8;
            2'b01:   nbits = 16;
            2'b10:   nbits = 32;
            default: nbits = 0;   // unused encoding: seed passes through
        endcase
        for (bi = nbits - 1; bi >= 0; bi = bi - 1) begin
            fb = c[15] ^ data[bi];
            c  = {c[14:0], 1'b0} ^ (fb ? 16'h1021 : 16'h0000);
        end
        ref_crc = c;
    end
endfunction

function [31:0] ref_imm;
    input [31:0] ins;
    begin
        case (ins[6:0])
            OP_LOAD, OP_ALU_IMM, OP_JALR:
                ref_imm = {{20{ins[31]}}, ins[31:20]};
            OP_STORE:
                ref_imm = {{20{ins[31]}}, ins[31:25], ins[11:7]};
            OP_BRANCH:
                ref_imm = {{19{ins[31]}}, ins[31], ins[7], ins[30:25], ins[11:8], 1'b0};
            OP_LUI, OP_AUIPC:
                ref_imm = {ins[31:12], 12'b0};
            OP_JAL:
                ref_imm = {{11{ins[31]}}, ins[31], ins[19:12], ins[20], ins[30:21], 1'b0};
            default:
                ref_imm = 32'b0;
        endcase
    end
endfunction

function ref_branch;
    input [2:0]  f3;
    input [31:0] a, b;
    begin
        case (f3)
            3'b000:  ref_branch = (a == b);
            3'b001:  ref_branch = (a != b);
            3'b100:  ref_branch = ($signed(a) <  $signed(b));
            3'b101:  ref_branch = ($signed(a) >= $signed(b));
            3'b110:  ref_branch = (a <  b);
            3'b111:  ref_branch = (a >= b);
            default: ref_branch = 1'b0;   // 010/011 are not branch encodings
        endcase
    end
endfunction

// Load extraction and extension. op_size is funct3: [1:0]=width, [2]=unsigned.
// Misaligned half/word accesses return a deterministic 0, never x.
function [31:0] ref_load;
    input [2:0]  f3;
    input [1:0]  off;
    input [31:0] word;
    reg   [7:0]  bb;
    reg   [15:0] hh;
    begin
        case (off)
            2'b00:   bb = word[7:0];
            2'b01:   bb = word[15:8];
            2'b10:   bb = word[23:16];
            default: bb = word[31:24];
        endcase
        case (off)
            2'b00:   hh = word[15:0];
            2'b10:   hh = word[31:16];
            default: hh = 16'b0;
        endcase
        case (f3[1:0])
            2'b00:   ref_load = f3[2] ? {24'b0, bb} : {{24{bb[7]}},  bb};
            2'b01:   ref_load = (off == 2'b00 || off == 2'b10)
                                ? (f3[2] ? {16'b0, hh} : {{16{hh[15]}}, hh})
                                : 32'b0;
            2'b10:   ref_load = (off == 2'b00) ? word : 32'b0;
            default: ref_load = 32'b0;
        endcase
    end
endfunction

function [3:0] ref_strobe;
    input [2:0] f3;
    input [1:0] off;
    input       valid_store;
    begin
        if (!valid_store) ref_strobe = 4'b0000;
        else case (f3[1:0])
            2'b00:   ref_strobe = 4'b0001 << off;
            2'b01:   ref_strobe = (off == 2'b00) ? 4'b0011 :
                                  (off == 2'b10) ? 4'b1100 : 4'b0000;
            2'b10:   ref_strobe = (off == 2'b00) ? 4'b1111 : 4'b0000;
            default: ref_strobe = 4'b0000;
        endcase
    end
endfunction

function [31:0] ref_store_data;
    input [2:0]  f3;
    input [1:0]  off;
    input [31:0] rs2;
    input        valid_store;
    begin
        if (!valid_store) ref_store_data = 32'b0;
        else case (f3[1:0])
            2'b00:   ref_store_data = {24'b0, rs2[7:0]} << (8*off);
            2'b01:   ref_store_data = (off == 2'b00) ? {16'b0, rs2[15:0]} :
                                      (off == 2'b10) ? {rs2[15:0], 16'b0} : 32'b0;
            2'b10:   ref_store_data = (off == 2'b00) ? rs2 : 32'b0;
            default: ref_store_data = 32'b0;
        endcase
    end
endfunction

