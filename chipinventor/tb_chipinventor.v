// ===========================================================================
//  SUITE 0.8 - CRC (replaces the golden vector file)
//
//  OPERAND ROLES: rs1 (u_a) carries the data, rs2 (u_b) carries the running
//  CRC. That is the order the official validation firmware uses -
//  "crcb s0, s1, s0" folds s1 into the accumulator held in s0 - and getting it
//  backwards is the one thing about this unit that a correct algorithm and a
//  correct check value will not catch, because CRCB(seed=X, data=Y) and
//  CRCB(seed=Y, data=X) are both perfectly valid CRC-16 computations. The
//  firmware anchor at the end of this task is what pins the order down.
// ===========================================================================
task suite_crc;
    reg [15:0] seed;
    reg [7:0]  msg [0:8];
    reg [7:0]  fw_b [0:7];
    reg [15:0] fw_h [0:3];
    reg [31:0] fw_w [0:1];
    begin
        f0 = 0;

        // The standard CRC-16/CCITT-FALSE check value: chaining CRCB over the
        // ASCII string "123456789" from seed 0xFFFF must give 0x29B1. This is
        // the hard gate on the algorithm being the right one.
        msg[0]=8'h31; msg[1]=8'h32; msg[2]=8'h33; msg[3]=8'h34; msg[4]=8'h35;
        msg[5]=8'h36; msg[6]=8'h37; msg[7]=8'h38; msg[8]=8'h39;
        seed = 16'hFFFF;
        u_f3 = 3'b000;
        for (k = 0; k < 9; k = k + 1) begin
            u_a = {24'b0, msg[k]};    // rs1 = data
            u_b = {16'b0, seed};      // rs2 = running CRC
            #1;
            seed = u_crcq[15:0];
        end
        if (seed === 16'h29B1) begin
            pass = pass + 1;
            $display("  CHECK-VALUE GATE: chained CRCB(\"123456789\") = 0x%h (expected 0x29B1) PASS", seed);
        end else begin
            f0 = f0 + 1;
            fail_msg("CRC check-value gate");
            $display("        got 0x%h, expected 0x29B1", seed);
        end

        // ---- Competition anchor: the three chains _rvbl2_crc_test runs -----
        // The official firmware compares each of these against 0x1E82 and
        // branches to _error otherwise. Replaying them here means a regression
        // in the operand order is caught by this unit test rather than showing
        // up as an opaque x4 = FFFFFFFF two suites later.
        fw_b[0]=8'h12; fw_b[1]=8'h34; fw_b[2]=8'h56; fw_b[3]=8'h78;
        fw_b[4]=8'h90; fw_b[5]=8'hAB; fw_b[6]=8'hCD; fw_b[7]=8'hEF;
        fw_h[0]=16'h1234; fw_h[1]=16'h5678; fw_h[2]=16'h90AB; fw_h[3]=16'hCDEF;
        fw_w[0]=32'h12345678; fw_w[1]=32'h90ABCDEF;

        seed = 16'hFFFF; u_f3 = 3'b000;
        for (k = 0; k < 8; k = k + 1) begin
            u_a = {24'b0, fw_b[k]}; u_b = {16'b0, seed}; #1; seed = u_crcq[15:0];
        end
        if (seed === 16'h1E82) pass = pass + 1;
        else begin
            f0 = f0 + 1; fail_msg("firmware anchor: 8x CRCB");
            $display("        got 0x%h, the validation firmware expects 0x1E82", seed);
        end

        seed = 16'hFFFF; u_f3 = 3'b001;
        for (k = 0; k < 4; k = k + 1) begin
            u_a = {16'b0, fw_h[k]}; u_b = {16'b0, seed}; #1; seed = u_crcq[15:0];
        end
        if (seed === 16'h1E82) pass = pass + 1;
        else begin
            f0 = f0 + 1; fail_msg("firmware anchor: 4x CRCH");
            $display("        got 0x%h, the validation firmware expects 0x1E82", seed);
        end

        seed = 16'hFFFF; u_f3 = 3'b010;
        for (k = 0; k < 2; k = k + 1) begin
            u_a = fw_w[k]; u_b = {16'b0, seed}; #1; seed = u_crcq[15:0];
        end
        if (seed === 16'h1E82) pass = pass + 1;
        else begin
            f0 = f0 + 1; fail_msg("firmware anchor: 2x CRCW");
            $display("        got 0x%h, the validation firmware expects 0x1E82", seed);
        end

        // Directed corners across all three widths. (u_a = data, u_b = seed.)
        for (k = 0; k < 3; k = k + 1) begin
            u_f3 = k[2:0];
            u_a = 32'h0000_0000; u_b = 32'h0000_0000; #1;
            if (u_crcq !== {16'b0, ref_crc(u_f3, 16'h0000, 32'h0)}) begin f0=f0+1; note_fail("CRC zero seed, zero data"); end
            u_a = 32'hFFFF_FFFF; u_b = 32'h0000_FFFF; #1;
            if (u_crcq !== {16'b0, ref_crc(u_f3, 16'hFFFF, 32'hFFFFFFFF)}) begin f0=f0+1; note_fail("CRC all-ones"); end
            u_a = 32'h0000_0000; u_b = 32'h0000_FFFF; #1;
            if (u_crcq !== {16'b0, ref_crc(u_f3, 16'hFFFF, 32'h0)}) begin f0=f0+1; note_fail("CRC ones seed, zero data"); end
        end

        // Only rs2[15:0] is the seed: the upper half must be ignored entirely.
        u_f3 = 3'b000; u_a = 32'h0000_005A;
        u_b = 32'h0000_1234; #1; k = u_crcq;
        u_b = 32'hFFFF_1234; #1;
        if (u_crcq === k) pass = pass + 1;
        else begin f0=f0+1; note_fail("CRC must ignore rs2[31:16]"); end

        // The data operand is the one that must be read at full width: a CRCW
        // has to see rs1[31:16], where a CRCB must not. This is the mirror of
        // the check above and fails if the two operands are ever swapped back.
        u_f3 = 3'b010; u_b = 32'h0000_FFFF;
        u_a = 32'h0000_1234; #1; k = u_crcq;
        u_a = 32'hABCD_1234; #1;
        if (u_crcq !== k) pass = pass + 1;
        else begin f0=f0+1; note_fail("CRCW must fold all 32 bits of rs1"); end

        // funct3=11 is not a CRC encoding; the seed passes through.
        u_f3 = 3'b011; u_b = 32'h0000_ABCD; u_a = 32'hFFFF_FFFF; #1;
        if (u_crcq === 32'h0000_ABCD) pass = pass + 1;
        else begin f0=f0+1; note_fail("CRC unused encoding must pass the seed through"); end

        // Randomised across all three widths against the reference model.
        for (n = 0; n < 600; n = n + 1) begin
            u_a  = $random;   // data
            u_b  = $random;   // seed
            u_f3 = n % 3;
            #1;
            if (u_crcq === {16'b0, ref_crc(u_f3, u_b[15:0], u_a)}) pass = pass + 1;
            else begin
                f0 = f0 + 1;
                note_fail("CRC randomised");
                if (fail_budget >= 0)
                    $display("        f3=%b seed=%h data=%h got=%h exp=%h",
                             u_f3, u_b[15:0], u_a, u_crcq, ref_crc(u_f3, u_b[15:0], u_a));
            end
        end

        if (f0 == 0) pass_msg("S0.8 CRC: check value, firmware anchor, three widths, 600 randomised");
        $display("  [S0.8] CRC-16/CCITT-FALSE: KAT gate, firmware 0x1E82 anchor, corners, 600 randomised");
    end
endtask

