task suite_imem;
    begin
        // The ROM holds two images:
        //   word   0..258  official validation firmware   (0x00400000)
        //   word 259..511  gap, reads back 0
        //   word 512..994  supplementary coverage program (0x00400800)
        // scripts/gen_ci_imem.py --check guards every word; these are the
        // landmarks that would catch a placement mistake - a misplaced image
        // would still be a self-consistent ROM and pass that check.
        p_oe = 1;

        // ---- official firmware, first three words --------------------------
        p_addr = IMEM_BASE + 0;  #1; check_imem(32'h123452b7, "official word 0 (lui t0,0x12345)");
        p_addr = IMEM_BASE + 4;  #1; check_imem(32'h12345337, "official word 1 (lui t1,0x12345)");
        p_addr = IMEM_BASE + 8;  #1; check_imem(32'h3e629463, "official word 2 (bne t0,t1,_error)");

        // ---- the two exit loops, which SUITE 2A synchronises on ------------
        p_addr = FW_PASS_LOOP - 4; #1; check_imem(32'h00000213, "all_good: addi x4, x0, 0");
        p_addr = FW_PASS_LOOP;     #1; check_imem(32'h0000006f, "all_good: j . (pass self-loop)");
        p_addr = FW_ERROR_PC;      #1; check_imem(32'hfff00213, "_error:   addi x4, x0, -1");
        p_addr = FW_FAIL_LOOP;     #1; check_imem(32'h0000006f, "_error:   j . (fail self-loop)");

        // ---- .rodata the firmware LOADS OUT OF IMEM ------------------------
        // These are constants, not instructions. Reaching them is the
        // ARCH_SPEC 7.4 case: IMEM is combinational with no output register,
        // so a load only resolves here because oe_o and the address mux stay
        // asserted through WRITEBACK.
        p_addr = 32'h004003F8; #1; check_imem(32'h12345678, "crc_data[0] in IMEM");
        p_addr = 32'h004003FC; #1; check_imem(32'h90abcdef, "crc_data[1] in IMEM");
        p_addr = 32'h00400400; #1; check_imem(32'h11111111, "source_data[0] in IMEM");
        p_addr = 32'h00400408; #1; check_imem(32'h33333333, "source_data[2] in IMEM");

        // ---- the gap between the two images --------------------------------
        p_addr = IMEM_BASE + 259*4; #1; check_imem(32'b0, "first word past the official image -> 0");
        p_addr = IMEM_BASE + 400*4; #1; check_imem(32'b0, "mid-gap -> 0, no aliasing");

        // ---- supplementary program at SUPP_BASE ----------------------------
        p_addr = SUPP_BASE + 0;  #1; check_imem(32'h10010a37, "supp word 0 (lui x20,0x10010)");
        p_addr = SUPP_BASE + 4;  #1; check_imem(32'h10010fb7, "supp word 1 (lui x31,0x10010)");
        p_addr = SUPP_BASE + 8;  #1; check_imem(32'h100f8f93, "supp word 2 (addi x31,x31,256)");

        // oe_i low must read a defined 0, not x.
        p_oe = 0; p_addr = IMEM_BASE; #1; check_imem(32'b0, "oe=0 reads defined 0");

        p_oe = 1;
        p_addr = SUPP_BASE + 483*4; #1; check_imem(32'b0, "one word past the supplementary image -> 0");

        // ---- the guard and the Stage 3 programs ----------------------------
        p_addr = S3_GPIO_LISTING - 4; #1; check_imem(32'h0000006f, "guard below the Stage 3 programs: j .");
        p_addr = S3_GPIO_LISTING;     #1; check_imem(32'hf0000437, "gpio_listing word 0 (lui s0,0xF0000)");
        p_addr = S3_GPIO_FIXED;       #1; check_imem(32'hf0000437, "gpio_fixed word 0 (lui s0,0xF0000)");
        p_addr = S3_ECHO_LISTING;     #1; check_imem(32'hf1000437, "echo_listing word 0 (lui s0,0xF1000)");
        p_addr = S3_ECHO_FIXED;       #1; check_imem(32'hf1000437, "echo_fixed word 0 (lui s0,0xF1000)");
        p_addr = S3_PERIPH_REGRESS + (S3_PERIPH_WORDS-1)*4; #1;
        check_imem(32'h0000006f, "periph_regress last word: j . (done)");

        // Past the end of every image but still inside the 4MB architectural
        // window: must read 0, never alias back into a real word.
        p_addr = S3_PERIPH_REGRESS + S3_PERIPH_WORDS*4;       #1; check_imem(32'b0, "one word past the ROM -> 0, no aliasing");
        p_addr = S3_PERIPH_REGRESS + S3_PERIPH_WORDS*4 + 128; #1; check_imem(32'b0, "further past the ROM -> 0");
        p_addr = IMEM_BASE + 32'h003F_FFFC;  #1; check_imem(32'b0, "top of 4MB window -> 0");
        p_oe = 0;
        $display("  [S0.9] IMEM: all seven images placed, guard, gaps read 0, oe gating, out-of-image reads");
    end
endtask

// ===========================================================================
//  SUITE 0.10 - DMEM
//  Signals are only changed a delta after a clock edge, never in the same
//  timestep the memory samples on: doing the latter is a genuine Verilog race
//  and it produced intermittently-skipped writes when this was first written.
// ===========================================================================
task dmem_write(input [31:0] a, input [31:0] d, input [3:0] mask);
    begin
        @(posedge clk); #1;
        m_addr = a; m_wd = d; m_bw = mask; m_we = 1; m_oe = 0;
        @(posedge clk); #1;
        m_we = 0;
    end
endtask

task dmem_read(input [31:0] a);
    begin
        @(posedge clk); #1;
        m_addr = a; m_oe = 1; m_we = 0;
        @(posedge clk);
        // Sample late in the cycle, where the register file actually captures
        // load data, rather than right at the edge.
        #9;
        m_oe = 0;
    end
endtask

