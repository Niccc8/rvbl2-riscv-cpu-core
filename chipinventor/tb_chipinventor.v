// Run the official firmware from reset until it settles into one of its two
// self-loops. `settled` reports whether it got there at all, so a hang is
// distinguishable from a genuine FAIL verdict.
task fw_run(output integer ran, output reg settled);
    integer hold;
    begin
        for (i = 0; i < 2048; i = i + 1) `DMEM_WORD(i) = 32'b0;
        rst = 1;
        repeat (3) @(posedge clk); #1;
        rst = 0;

        ran = 0; hold = 0; settled = 1'b0;
        while (ran < FW_CYCLE_CAP && !settled) begin
            @(posedge clk); #1;
            ran = ran + 1;
            if (`PC.pc === FW_PASS_LOOP || `PC.pc === FW_FAIL_LOOP) begin
                hold = hold + 1;
                if (hold >= FW_SETTLE) settled = 1'b1;
            end else begin
                hold = 0;
            end
        end
    end
endtask

task suite_official;
    integer ran;
    reg     settled;
    reg [31:0] verdict;
    begin
        fw_run(ran, settled);
        verdict = `RF.regs[FW_VERDICT_REG];

        // ---- did it finish at all? -----------------------------------------
        if (settled) begin
            pass = pass + 1;
            $display("  Firmware settled after %0d cycles at pc=%08h (%0s)",
                     ran, `PC.pc,
                     (`PC.pc === FW_PASS_LOOP) ? "all_good" : "_error");
        end else begin
            note_fail("official firmware never reached a completion loop");
            $display("        ran the full %0d-cycle budget, pc=%08h state=%0d",
                     ran, `PC.pc, `CTRL.state);
        end

        // ---- THE COMPETITION CRITERION -------------------------------------
        // "x4 = 0x00000000 -> PASS, x4 = 0xFFFFFFFF -> FAIL"
        if (verdict === FW_PASS) begin
            pass = pass + 1;
            $display("  ******************************************************");
            $display("  *  OFFICIAL VALIDATION FIRMWARE: x4 = %08h  PASS  *", verdict);
            $display("  ******************************************************");
        end else begin
            note_fail("OFFICIAL VALIDATION FIRMWARE FAILED");
            $display("        x4 = %08h (expected %08h)", verdict, FW_PASS);
            if (fw_err_seen) fw_report_subtest(fw_err_from);
            else $display("        _error was never entered - the run did not complete");
        end

        // Reaching the pass loop and leaving x4 clear must agree with each
        // other; if they ever disagree the run is not what it appears to be.
        if (settled && `PC.pc === FW_PASS_LOOP) begin
            if (verdict === FW_PASS) pass = pass + 1;
            else note_fail("reached all_good but x4 is not 0");
        end
        if (settled && `PC.pc === FW_FAIL_LOOP) begin
            if (verdict === FW_FAIL) pass = pass + 1;
            else note_fail("reached _error but x4 is not -1");
        end

        // ---- memory state, not just the verdict register -------------------
        // The firmware's own stores, checked independently of the branches it
        // used to check them. A core that computed the right comparisons but
        // wrote to the wrong place would still show x4 = 0.
        check_dmem_word(0, FW_DM0, "official: sw 0x12345678 to test_ram+0");
        check_dmem_word(1, FW_DM1, "official: sh 0xAABB to test_ram+4");
        check_dmem_word(2, FW_DM2, "official: sb 0xCC to test_ram+8");
        check_dmem_word(4, FW_DM4, "official: copy loop word 0 (IMEM -> DMEM)");
        check_dmem_word(5, FW_DM5, "official: copy loop word 1");
        check_dmem_word(6, FW_DM6, "official: copy loop word 2");

        // The copy loop read its source out of IMEM at 0x00400400 and the CRC
        // subtest read 0x004003F8, so a correct DMEM image here is also
        // positive evidence that loads resolving into IMEM work end to end.

        // x0 survived a whole validation run, including the firmware's own
        // "addi zero, zero, 1" probe.
        check_reg(0, 32'h0000_0000, "official: x0 still zero after the full run");

        $display("  [S2A] Official validation firmware: %0d cycles, verdict x4=%08h",
                 ran, verdict);
    end
endtask

// Log every firmware-completion pulse with its cycle and PC, which is the
// evidence the Submission Guide's firmware demo asks for.
always @(posedge clk) begin
    if (rst === 1'b0 && `CTRL.sys_event_o === 1'b1) begin
        event_count = event_count + 1;
        $display("  [sys_event_o pulse #%0d] cycle=%0d pc=%h", event_count, cyc, `PC.pc);
    end
end

// ---------------------------------------------------------------------------
// SUITE 2B support: entering the supplementary program.
//
// The ROM's reset vector belongs to the official firmware, so this program is
// entered by pointing the PC at it while the core is still in reset. That is
// safe because pc_write is only asserted in EXECUTE(branch), MEMORY(store) and
// WRITEBACK - the PC holds through RESET, FETCH and DECODE, so the value
// written here is the one the first fetch uses.
//
// This is the one place the suite depends on a hierarchical procedural write
// to a register inside the design (DMEM zeroing aside). If a simulator ever
// refuses it, the fallback is to run this program as a separate project with
// the ROM's two segments swapped.
// ---------------------------------------------------------------------------
task enter_supplementary;
    begin
        for (i = 0; i < 2048; i = i + 1) `DMEM_WORD(i) = 32'b0;
        rst = 1;
        repeat (3) @(posedge clk); #1;
        `PC.pc = SUPP_BASE;   // still in reset; the next edge holds it
        rst = 0;
    end
endtask

task suite_integration;
    integer sig_fail;
    reg [31:0] sig_word;
    begin
        cyc = 0; event_count = 0;
        enter_supplementary;

        // The entry point has to actually stick, or every check below would be
        // testing the official firmware's leftovers instead.
        if (`PC.pc === SUPP_BASE) pass = pass + 1;
        else begin
            note_fail("supplementary program entry point did not take");
            $display("        pc=%08h, expected %08h", `PC.pc, SUPP_BASE);
        end

        // A fixed budget is safer than synchronising on "the" completion pulse,
        // since the program legitimately produces two (EBREAK, then ECALL).
        repeat (6000) begin
            @(posedge clk); #1;
            cyc = cyc + 1;
        end

        $display("  Ran %0d cycles, observed %0d sys_event_o pulses (expect 2: EBREAK then ECALL)",
                 cyc, event_count);
        if (event_count == 2) pass = pass + 1;
        else begin
            note_fail("expected exactly 2 sys_event_o pulses");
            $display("        got %0d", event_count);
        end

        // Every instruction test stores (actual XOR expected) into its own
        // signature slot, so a zero word means that instruction passed.
        sig_fail = 0;
        for (i = 0; i < NUM_SIG_TESTS; i = i + 1) begin
            sig_word = `DMEM_WORD(SIG_BASE_WORDS + i);
            if (sig_word === 32'b0) pass = pass + 1;
            else begin
                sig_fail = sig_fail + 1;
                note_fail("instruction signature non-zero");
                if (fail_budget >= 0)
                    $display("        signature[%0d] diff=%h", i, sig_word);
            end
        end
        $display("  Signature-based instruction tests: %0d/%0d passed",
                 NUM_SIG_TESTS - sig_fail, NUM_SIG_TESTS);

        // Structural checks for the instructions a signature slot cannot cover.
        check_reg(7,  32'h0000_0000, "x7 skipped by JAL");
        check_reg(8,  32'h0000_0001, "x8 proves JAL landed");
        check_reg(9,  EXP_JALR_LINK, "x9 JALR link address");
        check_reg(11, 32'h0000_0001, "x11 reached once via the JALR return path");
        check_reg(12, 32'h0000_0001, "x12 proves JALR landed");
        check_reg(13, 32'h0000_0001, "x13 control flow rejoined after JALR");
        check_reg(14, EXP_AUIPC,     "x14 AUIPC = pc + (5<<12)");
        check_reg(15, 32'h0000_0077, "x15 sentinel before FENCE");
        check_reg(16, 32'h0000_0077, "x16 FENCE was a pure no-op");
        check_reg(17, 32'h0000_0088, "x17 sentinel before EBREAK");
        check_reg(18, 32'h0000_0088, "x18 EBREAK was a pure no-op");

        // The load-from-IMEM timing case. IMEM is combinational with no output
        // register, so this only reads back the real constant because oe_o and
        // the address mux stay asserted through WRITEBACK.
        check_reg(22, EXP_IMEM_LOAD, "x22 load resolved into IMEM, not DMEM");
        check_reg(23, 32'h0000_0001, "x23 control flow survived the IMEM load");

        // Dependent-register loop: hazard-free by construction.
        check_reg(24, EXP_DEP_SUM,   "x24 dependent-loop sum 1..5");
        check_reg(25, EXP_DEP_CTR,   "x25 dependent-loop counter on exit");
        check_reg(27, 32'h0000_0001, "x27 dependent loop exited normally");

        // x0 must still be zero after a whole program's worth of writes.
        check_reg(0, 32'h0000_0000, "x0 hardwired zero after full program");
        $display("  [S2B] Integration: supplementary program at %08h, %0d instruction signatures, structural checks",
                 SUPP_BASE, NUM_SIG_TESTS);
    end
endtask

// ===========================================================================
//  SUITE 3 - reset stress
//  The unit-level check confirms the combinational enables drop the same cycle
//  reset asserts. What that cannot see is whether an in-flight DMEM write is
//  genuinely aborted before it commits, which is what this injects for.
//
//  3.1 injects reset at forty points in the OFFICIAL firmware, since that is
//      what runs from the reset vector.
//  3.2 then requires the official firmware to still reach x4 = 0 afterwards -
//      recovering to the competition's own verdict is a stronger claim than
//      recovering to signatures we chose ourselves.
//  3.3 does the same for the supplementary program and its 58 signatures.
// ===========================================================================
localparam INJECT_POINTS = 40;
localparam WATCH_LOW     = 16;   // words the early program writes
localparam WATCH_SIG     = 16;   // first signature slots

reg [31:0] snap_low [0:WATCH_LOW-1];
reg [31:0] snap_sig [0:WATCH_SIG-1];

task suite_reset;
    integer inj;
    begin
        for (inj = 1; inj <= INJECT_POINTS; inj = inj + 1) begin
            rst = 1; repeat (3) @(posedge clk); #1;
            rst = 0;
            repeat (inj) @(posedge clk);
            #1;

            for (i = 0; i < WATCH_LOW; i = i + 1) snap_low[i] = `DMEM_WORD(i);
            for (i = 0; i < WATCH_SIG; i = i + 1) snap_sig[i] = `DMEM_WORD(SIG_BASE_WORDS + i);

            rst = 1;            // assert mid-instruction
            @(posedge clk); #1; // the edge reset must abort

            for (i = 0; i < WATCH_LOW; i = i + 1) begin
                if (`DMEM_WORD(i) === snap_low[i]) pass = pass + 1;
                else begin
                    note_fail("DMEM word changed across the reset edge");
                    if (fail_budget >= 0)
                        $display("        inj=%0d word %0d: %h -> %h",
                                 inj, i, snap_low[i], `DMEM_WORD(i));
                end
            end
            for (i = 0; i < WATCH_SIG; i = i + 1) begin
                if (`DMEM_WORD(SIG_BASE_WORDS + i) === snap_sig[i]) pass = pass + 1;
                else begin
                    note_fail("signature word changed across the reset edge");
                    if (fail_budget >= 0)
                        $display("        inj=%0d signature %0d: %h -> %h",
                                 inj, i, snap_sig[i], `DMEM_WORD(SIG_BASE_WORDS + i));
                end
            end

            if (`PC.pc === 32'h0040_0000) pass = pass + 1;
            else begin
                note_fail("PC not at the reset vector after reset");
                if (fail_budget >= 0) $display("        inj=%0d pc=%h", inj, `PC.pc);
            end

            if (`CTRL.state === S_RESET) pass = pass + 1;
            else begin
                note_fail("FSM not in RESET after reset");
                if (fail_budget >= 0) $display("        inj=%0d state=%0d", inj, `CTRL.state);
            end

            for (i = 0; i < 32; i = i + 1) begin
                if (`RF.regs[i] === 32'd0) pass = pass + 1;
                else begin
                    note_fail("GPR not cleared by reset");
                    if (fail_budget >= 0)
                        $display("        inj=%0d x%0d=%h", inj, i, `RF.regs[i]);
                end
            end
        end
        $display("  [S3.1] Reset injected at %0d points of the official firmware: writes aborted, PC/FSM/GPRs cleared",
                 INJECT_POINTS);
    end
endtask

task suite_reset_official;
    integer ran;
    reg     settled;
    reg [31:0] verdict;
    begin
        // Reset must leave the core genuinely usable, not merely quiet. The
        // strongest available statement of that is that the competition's own
        // firmware still passes after the core has been reset mid-instruction
        // forty times.
        fw_run(ran, settled);
        verdict = `RF.regs[FW_VERDICT_REG];

        if (settled) pass = pass + 1;
        else begin
            note_fail("post-reset re-run: official firmware did not complete");
            $display("        pc=%08h after %0d cycles", `PC.pc, ran);
        end

        if (verdict === FW_PASS) pass = pass + 1;
        else begin
            note_fail("post-reset re-run: official firmware verdict is not PASS");
            $display("        x4 = %08h", verdict);
            if (fw_err_seen) fw_report_subtest(fw_err_from);
        end

        check_dmem_word(0, FW_DM0, "post-reset re-run: official DMEM word 0");
        check_dmem_word(6, FW_DM6, "post-reset re-run: official copy loop word 2");

        $display("  [S3.2] Reset recovery: the official firmware still returns x4=%08h after %0d cycles",
                 verdict, ran);
    end
endtask

task suite_reset_recovery;
    begin
        // The same claim for the supplementary program, which is what covers
        // FENCE, ECALL, EBREAK and the 58 instruction signatures.
        cyc = 0;
        enter_supplementary;
        repeat (6000) begin
            @(posedge clk); #1;
            cyc = cyc + 1;
        end

        check_reg(22, EXP_IMEM_LOAD, "post-reset re-run: IMEM load still correct");
        check_reg(24, EXP_DEP_SUM,   "post-reset re-run: dependent loop still correct");
        check_reg(18, 32'h0000_0088, "post-reset re-run: EBREAK still a no-op");

        f0 = 0;
        for (i = 0; i < NUM_SIG_TESTS; i = i + 1)
            if (`DMEM_WORD(SIG_BASE_WORDS + i) !== 32'b0) f0 = f0 + 1;
        if (f0 == 0) pass = pass + 1;
        else begin
            note_fail("post-reset re-run: instruction signatures not all zero");
            $display("        %0d of %0d slots non-zero", f0, NUM_SIG_TESTS);
        end
        $display("  [S3.3] Reset recovery: supplementary program re-runs to an identical result");
    end
endtask

