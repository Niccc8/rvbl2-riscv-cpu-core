task suite_dec;
    begin
        d_imemrd = 32'hAAAA_AAAA; d_dmemrd = 32'hBBBB_BBBB;

        d_we=0; d_oe=1; d_bw=4'b0000;
        d_addr = IMEM_BASE;     #1; check_dec(1,0,0,4'b0000, 32'hAAAA_AAAA, "IMEM base");
        d_addr = IMEM_LAST;     #1; check_dec(1,0,0,4'b0000, 32'hAAAA_AAAA, "IMEM last byte");
        d_addr = IMEM_BASE - 1; #1; check_dec(0,0,0,4'b0000, 32'b0, "just below IMEM base -> unmapped");
        d_addr = IMEM_LAST + 1; #1; check_dec(0,0,0,4'b0000, 32'b0, "just above IMEM last -> unmapped");

        d_addr = DMEM_BASE;     #1; check_dec(0,0,1,4'b0000, 32'hBBBB_BBBB, "DMEM base");
