//  RV32I + Zmmul + Xicrc, 47 instructions
// ----------------------------------------------------------------------------
//  ChipInventor runs testbenches only at project level, so the sixteen
//  separate testbenches this design was verified with are combined here into
//  one file. Nothing is instantiated twice: the project's own `top` runs the
//  integration suites, and the unit suites instantiate individual blocks
//  directly, which works because the generated project file defines every
//  block module alongside `top`.
//
//  SUITE 0  Unit tests - every block on its own, directed corners plus
//           randomised sweeps against reference models written independently
//           of the RTL. Runs while the core is held in reset.
//  SUITE 1  Control FSM - a standalone control_unit driven through every
//           {opcode, funct3, funct7} combination the ISA can express.
//  SUITE 2A OFFICIAL VALIDATION FIRMWARE - the competition's own image, run
//           from the reset vector. Verdict is x4: 0 = PASS, -1 = FAIL.
//  SUITE 2B Integration - this project's supplementary program, covering what
//           the official firmware does not reach (FENCE, ECALL, EBREAK,
//           illegal instructions, misaligned access, 58 signatures).
//  SUITE 3  Reset stress - reset injected at forty different points in a
//           running program, checking in-flight writes are actually aborted,
//           then requiring both programs to still complete correctly.
//  SUITE 4  Stage 3 peripherals - gpio, uart and gpio_bits on their own, then
