    end
endtask

reg [31:0] corner [0:6];
integer c1, c2;

task suite_mult;
    reg [2:0] fn3;
    reg exp_as, exp_bs, exp_up, got_as, got_bs, got_up;
    begin
        corner[0] = 32'h0000_0000;
        corner[1] = 32'h0000_0001;
        corner[2] = 32'hFFFF_FFFF; // -1
        corner[3] = 32'h8000_0000; // INT_MIN
        corner[4] = 32'h7FFF_FFFF; // INT_MAX
        corner[5] = 32'h0000_0002;
        corner[6] = 32'hFFFF_FFFE; // -2

        for (c1 = 0; c1 < 7; c1 = c1 + 1) begin
            for (c2 = 0; c2 < 7; c2 = c2 + 1) begin
                u_a = corner[c1]; u_b = corner[c2];
                u_f3 = 3'b000; check_mult("MUL corner");
                u_f3 = 3'b001; check_mult("MULH corner");
                u_f3 = 3'b010; check_mult("MULHSU corner");
                u_f3 = 3'b011; check_mult("MULHU corner");
            end
        end

        // INT_MIN * -1: must wrap, not trap.
        u_a = 32'h8000_0000; u_b = 32'hFFFF_FFFF;
        u_f3 = 3'b000; check_mult("MUL INT_MIN*-1 wraps");
        u_f3 = 3'b001; check_mult("MULH INT_MIN*-1");

        for (n = 0; n < 500; n = n + 1) begin
            u_a = $random; u_b = $random;
            u_f3 = 3'b000; check_mult("MUL randomised");
            u_f3 = 3'b001; check_mult("MULH randomised");
            u_f3 = 3'b010; check_mult("MULHSU randomised");
            u_f3 = 3'b011; check_mult("MULHU randomised");
        end

        // Brute-force check of the operand-signedness formulas themselves
        // against the Table 10 truth table. funct3[0] alone would be wrong for
        // MULHSU, which is exactly why the design uses funct3[1]|funct3[0].
        for (fn3 = 0; fn3 < 4; fn3 = fn3 + 1) begin
            case (fn3)
                3'b000: begin exp_as=1; exp_bs=1; exp_up=0; end // MUL
                3'b001: begin exp_as=1; exp_bs=1; exp_up=1; end // MULH
                3'b010: begin exp_as=1; exp_bs=0; exp_up=1; end // MULHSU
                default:begin exp_as=0; exp_bs=0; exp_up=1; end // MULHU
            endcase
            got_as = ~(fn3[1] & fn3[0]);
            got_bs = ~fn3[1];
            got_up = fn3[1] | fn3[0];
            if (got_as===exp_as && got_bs===exp_bs && got_up===exp_up) pass = pass + 1;
            else begin
                note_fail("MULT truth table");
                $display("        funct3=%b a_signed=%b(exp %b) b_signed=%b(exp %b) sel_upper=%b(exp %b)",
                         fn3, got_as, exp_as, got_bs, exp_bs, got_up, exp_up);
            end
        end
        $display("  [S0.4] Multiplier: 4 ops, 49 corner pairs, 2000 randomised, truth table");
    end
endtask

