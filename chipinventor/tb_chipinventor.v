task suite_imem;
    begin
        // The ROM holds two images:
        //   word   0..258  official validation firmware   (0x00400000)
        //   word 259..511  gap, reads back 0
        //   word 512..994  supplementary coverage program (0x00400800)
        // scripts/gen_ci_imem.py --check guards every word; these are the
        // landmarks that would catch a placement mistake - a misplaced image
        // would still be a self-consistent ROM and pass that check.
        p_oe = 1;

        // ---- official firmware, first three words --------------------------
        p_addr = IMEM_BASE + 0;  #1; check_imem(32'h123452b7, "official word 0 (lui t0,0x12345)");
        p_addr = IMEM_BASE + 4;  #1; check_imem(32'h12345337, "official word 1 (lui t1,0x12345)");
        p_addr = IMEM_BASE + 8;  #1; check_imem(32'h3e629463, "official word 2 (bne t0,t1,_error)");

        // ---- the two exit loops, which SUITE 2A synchronises on ------------
        p_addr = FW_PASS_LOOP - 4; #1; check_imem(32'h00000213, "all_good: addi x4, x0, 0");
        p_addr = FW_PASS_LOOP;     #1; check_imem(32'h0000006f, "all_good: j . (pass self-loop)");
        p_addr = FW_ERROR_PC;      #1; check_imem(32'hfff00213, "_error:   addi x4, x0, -1");
        p_addr = FW_FAIL_LOOP;     #1; check_imem(32'h0000006f, "_error:   j . (fail self-loop)");

        // ---- .rodata the firmware LOADS OUT OF IMEM ------------------------
        // These are constants, not instructions. Reaching them is the
        // ARCH_SPEC 7.4 case: IMEM is combinational with no output register,
        // so a load only resolves here because oe_o and the address mux stay
        // asserted through WRITEBACK.
        p_addr = 32'h004003F8; #1; check_imem(32'h12345678, "crc_data[0] in IMEM");
        p_addr = 32'h004003FC; #1; check_imem(32'h90abcdef, "crc_data[1] in IMEM");
        p_addr = 32'h00400400; #1; check_imem(32'h11111111, "source_data[0] in IMEM");
        p_addr = 32'h00400408; #1; check_imem(32'h33333333, "source_data[2] in IMEM");

        // ---- the gap between the two images --------------------------------
        p_addr = IMEM_BASE + 259*4; #1; check_imem(32'b0, "first word past the official image -> 0");
        p_addr = IMEM_BASE + 400*4; #1; check_imem(32'b0, "mid-gap -> 0, no aliasing");

        // ---- supplementary program at SUPP_BASE ----------------------------
        p_addr = SUPP_BASE + 0;  #1; check_imem(32'h10010a37, "supp word 0 (lui x20,0x10010)");
        p_addr = SUPP_BASE + 4;  #1; check_imem(32'h10010fb7, "supp word 1 (lui x31,0x10010)");
        p_addr = SUPP_BASE + 8;  #1; check_imem(32'h100f8f93, "supp word 2 (addi x31,x31,256)");

        // oe_i low must read a defined 0, not x.
        p_oe = 0; p_addr = IMEM_BASE; #1; check_imem(32'b0, "oe=0 reads defined 0");

        // Past the end of both images but still inside the 4MB architectural
        // window: must read 0, never alias back into a real word.
        p_oe = 1;
        p_addr = SUPP_BASE + 483*4;       #1; check_imem(32'b0, "one word past the ROM -> 0, no aliasing");
        p_addr = SUPP_BASE + 483*4 + 128; #1; check_imem(32'b0, "further past the ROM -> 0");
        p_addr = IMEM_BASE + 32'h003F_FFFC;  #1; check_imem(32'b0, "top of 4MB window -> 0");
        p_oe = 0;
        $display("  [S0.9] IMEM: both images placed, gap reads 0, oe gating, out-of-image reads");
    end
endtask

// ===========================================================================
//  SUITE 0.10 - DMEM
//  Signals are only changed a delta after a clock edge, never in the same
//  timestep the memory samples on: doing the latter is a genuine Verilog race
//  and it produced intermittently-skipped writes when this was first written.
// ===========================================================================
task dmem_write(input [31:0] a, input [31:0] d, input [3:0] mask);
    begin
        @(posedge clk); #1;
        m_addr = a; m_wd = d; m_bw = mask; m_we = 1; m_oe = 0;
        @(posedge clk); #1;
        m_we = 0;
    end
endtask

task dmem_read(input [31:0] a);
    begin
        @(posedge clk); #1;
        m_addr = a; m_oe = 1; m_we = 0;
        @(posedge clk);
        // Sample late in the cycle, where the register file actually captures
        // load data, rather than right at the edge.
        #9;
        m_oe = 0;
    end
endtask

task check_dmem(input [31:0] exp, input [8*72-1:0] name);
    begin
        if (m_rd === exp) pass = pass + 1;
        else begin
            note_fail(name);
            if (fail_budget >= 0) $display("        got=%h exp=%h", m_rd, exp);
        end
    end
endtask

task suite_dmem;
    begin
        m_we=0; m_oe=0; m_bw=0; m_addr=0; m_wd=0;
        for (i = 0; i < MWORDS; i = i + 1) U_DMEM.mem[i] = 32'b0;
        @(posedge clk); #1;

        dmem_write(32'h1001_0000, 32'hCAFE_BABE, 4'b1111);
        dmem_read(32'h1001_0000);
        check_dmem(32'hCAFE_BABE, "full-word write then registered read-back");

        dmem_write(32'h1001_0000, 32'h00AA_0000, 4'b0100);
        dmem_read(32'h1001_0000);
        check_dmem(32'hCAAA_BABE, "single byte lane preserves the other three");

        dmem_write(32'h1001_0004, 32'h1111_2222, 4'b1111);
        repeat (5) @(posedge clk);
        dmem_read(32'h1001_0004);
        check_dmem(32'h1111_2222, "write survives idle cycles (true storage)");

        dmem_write(32'h1001_0008, 32'hFFFF_FFFF, 4'b1111);
        dmem_write(32'h1001_0008, 32'h0000_00AA, 4'b0001);
        dmem_read(32'h1001_0008); check_dmem(32'hFFFF_FFAA, "lane 0 only");
        dmem_write(32'h1001_0008, 32'h0000_BB00, 4'b0010);
        dmem_read(32'h1001_0008); check_dmem(32'hFFFF_BBAA, "lane 1 only");
        dmem_write(32'h1001_0008, 32'h00CC_0000, 4'b0100);
        dmem_read(32'h1001_0008); check_dmem(32'hFFCC_BBAA, "lane 2 only");
        dmem_write(32'h1001_0008, 32'hDD00_0000, 4'b1000);
        dmem_read(32'h1001_0008); check_dmem(32'hDDCC_BBAA, "lane 3 only");

        // Simultaneous we/oe cannot occur given the FSM's scoping, but if it
        // ever did the behaviour must be deterministic write-wins.
        @(posedge clk); #1;
        m_addr = 32'h1001_000C; m_wd = 32'h5555_5555; m_bw = 4'b1111; m_we = 1; m_oe = 1;
        @(posedge clk); #1; m_we = 0; m_oe = 0;
        dmem_read(32'h1001_000C);
        check_dmem(32'h5555_5555, "simultaneous we and oe -> write wins");

        dmem_write(32'h1001_0010, 32'hAAAA_BBBB, 4'b1111);
        dmem_write(32'h1001_0014, 32'hCCCC_DDDD, 4'b1111);
        dmem_read(32'h1001_0010); check_dmem(32'hAAAA_BBBB, "non-adjacent word A independent");
        dmem_read(32'h1001_0014); check_dmem(32'hCCCC_DDDD, "non-adjacent word B independent");

        dmem_read(32'h1001_0020);
        check_dmem(32'h0000_0000, "never-written word reads 0");

        dmem_write(32'h1001_0018, 32'hFFFF_FFFF, 4'b1111);
        dmem_write(32'h1001_0018, 32'h0000_5678, 4'b0011);
        dmem_read(32'h1001_0018); check_dmem(32'hFFFF_5678, "half-word write lanes 0+1");

        dmem_write(32'h1001_001C, 32'h0000_0000, 4'b1111);
        dmem_write(32'h1001_001C, 32'h9ABC_0000, 4'b1100);
        dmem_read(32'h1001_001C); check_dmem(32'h9ABC_0000, "half-word write lanes 2+3");

        dmem_write(32'h1001_0000 + (MWORDS-1)*4, 32'hDEAD_BEEF, 4'b1111);
        dmem_read(32'h1001_0000 + (MWORDS-1)*4);
        check_dmem(32'hDEAD_BEEF, "last implemented word");

        // Inside the architectural 8kB window but past the instantiated array:
        // must read 0 and write nothing, never alias into a real word. This is
        // the guard that makes DMEM_WORDS a safe resize knob.
        dmem_write(32'h1001_0000, 32'hA5A5_A5A5, 4'b1111);
        dmem_write(32'h1001_0080, 32'hDEAD_BEEF, 4'b1111);
        dmem_read(32'h1001_0000);
        check_dmem(32'hA5A5_A5A5, "out-of-range write must not alias into word 0");
        dmem_read(32'h1001_0080);
        check_dmem(32'h0000_0000, "out-of-range read returns 0, not an aliased word");
        dmem_read(32'h1001_1FFC);
        check_dmem(32'h0000_0000, "read at top of window, past array -> 0");
        $display("  [S0.10] DMEM: byte lanes, storage, aliasing prevention");
    end
endtask

// ===========================================================================
//  SUITE 0.11 - glue blocks
//  These carry logic that used to live inline in riscv_core, so they are the
//  parts of the design with no prior test history at all.
// ===========================================================================
task suite_glue;
    begin
        f0 = 0;

        // mux2_32: s selects b, not a.
        u_a = 32'hAAAA_AAAA; u_b = 32'h5555_5555;
        g_s = 1'b0; #1; if (g_muxz !== 32'hAAAA_AAAA) begin f0=f0+1; note_fail("mux2_32 s=0 must select a"); end
        g_s = 1'b1; #1; if (g_muxz !== 32'h5555_5555) begin f0=f0+1; note_fail("mux2_32 s=1 must select b"); end
        for (n = 0; n < 200; n = n + 1) begin
            u_a = $random; u_b = $random; g_s = n[0]; #1;
            if (g_muxz === (g_s ? u_b : u_a)) pass = pass + 1;
            else begin f0=f0+1; note_fail("mux2_32 randomised"); end
        end

        // wb_mux_32: every defined select, plus the undefined ones falling
        // through to the ALU result exactly as the original case default did.
        g_alu=32'h1111_1111; g_mul=32'h2222_2222; g_crc=32'h3333_3333;
        g_load=32'h4444_4444; g_pc4=32'h5555_5555;
        g_wbsel=3'b000; #1; if (g_wbz!==g_alu)  begin f0=f0+1; note_fail("wb_mux 000 -> alu_result"); end else pass=pass+1;
        g_wbsel=3'b001; #1; if (g_wbz!==g_mul)  begin f0=f0+1; note_fail("wb_mux 001 -> mult_result"); end else pass=pass+1;
        g_wbsel=3'b010; #1; if (g_wbz!==g_crc)  begin f0=f0+1; note_fail("wb_mux 010 -> crc_result"); end else pass=pass+1;
        g_wbsel=3'b011; #1; if (g_wbz!==g_load) begin f0=f0+1; note_fail("wb_mux 011 -> lsu_load_data"); end else pass=pass+1;
        g_wbsel=3'b100; #1; if (g_wbz!==g_pc4)  begin f0=f0+1; note_fail("wb_mux 100 -> pc_plus_4"); end else pass=pass+1;
        g_wbsel=3'b101; #1; if (g_wbz!==g_alu)  begin f0=f0+1; note_fail("wb_mux 101 -> alu_result (default)"); end else pass=pass+1;
        g_wbsel=3'b110; #1; if (g_wbz!==g_alu)  begin f0=f0+1; note_fail("wb_mux 110 -> alu_result (default)"); end else pass=pass+1;
        g_wbsel=3'b111; #1; if (g_wbz!==g_alu)  begin f0=f0+1; note_fail("wb_mux 111 -> alu_result (default)"); end else pass=pass+1;

        // ir_fields: the extraction the canvas cannot do with a wire.
        u_ins = 32'hFFFF_FFFF; #1;
        if (g_rs1===5'h1F && g_rs2===5'h1F && g_rd===5'h1F) pass=pass+1;
        else begin f0=f0+1; note_fail("ir_fields all-ones"); end
        u_ins = 32'h0000_0000; #1;
        if (g_rs1===5'h00 && g_rs2===5'h00 && g_rd===5'h00) pass=pass+1;
        else begin f0=f0+1; note_fail("ir_fields all-zeros"); end
        for (n = 0; n < 300; n = n + 1) begin
            u_ins = $random; #1;
            if (g_rs1 === u_ins[19:15] && g_rs2 === u_ins[24:20] && g_rd === u_ins[11:7]) pass = pass + 1;
            else begin
                f0 = f0 + 1;
                note_fail("ir_fields randomised");
                if (fail_budget >= 0)
                    $display("        ir=%h rs1=%h(%h) rs2=%h(%h) rd=%h(%h)", u_ins,
                             g_rs1, u_ins[19:15], g_rs2, u_ins[24:20], g_rd, u_ins[11:7]);
            end
        end

