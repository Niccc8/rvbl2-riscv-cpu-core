        l_addr=32'h1001_0001; u_f3=3'b010; #1; check_store(4'b0000, 32'b0, "SW misaligned -> no write");

        // is_valid_store gating: a perfectly aligned access must still produce
        // bw=0000 when the current instruction is not a store.
        l_store = 0;
        l_addr=32'h1001_0000; u_f3=3'b000; l_rs2=32'hFF; #1;
        check_store(4'b0000, 32'b0, "is_valid_store=0 forces bw=0000");

        // Randomised across every funct3 and byte offset, both paths.
        for (n = 0; n < 1500; n = n + 1) begin
            l_addr  = $random;
            l_rs2   = $random;
            l_memrd = $random;
            u_f3    = n % 8;
            l_store = n[3];
            #1;
            if (l_load === ref_load(u_f3, l_addr[1:0], l_memrd)) pass = pass + 1;
            else begin
                note_fail("LSU load randomised");
                if (fail_budget >= 0)
                    $display("        f3=%b off=%b got=%h exp=%h",
                             u_f3, l_addr[1:0], l_load, ref_load(u_f3, l_addr[1:0], l_memrd));
            end
            if (l_bw === ref_strobe(u_f3, l_addr[1:0], l_store) &&
                l_sdata === ref_store_data(u_f3, l_addr[1:0], l_rs2, l_store)) pass = pass + 1;
            else begin
                note_fail("LSU store randomised");
                if (fail_budget >= 0)
                    $display("        f3=%b off=%b store=%b got bw=%b data=%h exp bw=%b data=%h",
                             u_f3, l_addr[1:0], l_store, l_bw, l_sdata,
                             ref_strobe(u_f3, l_addr[1:0], l_store),
                             ref_store_data(u_f3, l_addr[1:0], l_rs2, l_store));
            end
        end
        $display("  [S0.5] LSU: 8 funct3 x 4 offsets, both paths, 3000 randomised checks");
    end
endtask

