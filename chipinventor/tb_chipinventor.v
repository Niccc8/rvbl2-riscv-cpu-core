        d_addr = DMEM_BASE - 1; #1; check_dec(0,0,0,4'b0000, 32'b0, "just below DMEM base -> unmapped");
        d_addr = DMEM_LAST + 1; #1; check_dec(0,0,0,4'b0000, 32'b0, "just above DMEM last -> unmapped");

