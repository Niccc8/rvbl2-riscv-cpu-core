// ===========================================================================
//  SUITE 1 - control unit
// ===========================================================================
localparam [2:0] C_ILLEGAL = 3'd0,  // incl. FENCE / ECALL / EBREAK: no rd write
                 C_WRITES  = 3'd1,
                 C_LOAD    = 3'd2,
                 C_STORE   = 3'd3,
                 C_BRANCH  = 3'd4;

// An independent classifier derived from the ISA tables, deliberately not
// copied from control_unit's own decode expressions.
function [2:0] ref_class;
    input [31:0] instr;
    reg [6:0] opcode, funct7;
    reg [2:0] funct3;
    reg       shift_ok;
    begin
        opcode = instr[6:0];
        funct3 = instr[14:12];
        funct7 = instr[31:25];
        case (opcode)
            OP_ALU_REG:
                ref_class = ((funct7==7'b0000000) ||
                             ((funct7==7'b0100000) && (funct3==3'b000 || funct3==3'b101)) ||
                             ((funct7==7'b0000001) && (funct3[2]==1'b0)) ||
                             ((funct7==7'b1000000) && (funct3==3'b000||funct3==3'b001||funct3==3'b010)))
                            ? C_WRITES : C_ILLEGAL;
            OP_ALU_IMM: begin
                shift_ok = (funct3==3'b001) ? (funct7==7'b0000000)
                                            : ((funct7==7'b0000000)||(funct7==7'b0100000));
                ref_class = ((funct3!=3'b001 && funct3!=3'b101) || shift_ok) ? C_WRITES : C_ILLEGAL;
            end
            OP_LOAD:   ref_class = (funct3==3'b000||funct3==3'b001||funct3==3'b010||
                                    funct3==3'b100||funct3==3'b101) ? C_LOAD : C_ILLEGAL;
            OP_STORE:  ref_class = (funct3==3'b000||funct3==3'b001||funct3==3'b010)
                                   ? C_STORE : C_ILLEGAL;
            OP_BRANCH: ref_class = (funct3==3'b000||funct3==3'b001||funct3==3'b100||
                                    funct3==3'b101||funct3==3'b110||funct3==3'b111)
                                   ? C_BRANCH : C_ILLEGAL;
            OP_JAL:    ref_class = C_WRITES;
            OP_JALR:   ref_class = (funct3==3'b000) ? C_WRITES : C_ILLEGAL;
            OP_LUI:    ref_class = C_WRITES;
            OP_AUIPC:  ref_class = C_WRITES;
            OP_SYSTEM: ref_class = C_ILLEGAL;   // ECALL/EBREAK take the no-result path too
            OP_FENCE:  ref_class = C_ILLEGAL;
            default:   ref_class = C_ILLEGAL;
        endcase
    end
endfunction

task ctrl_hard_reset;
    begin
        c_rst = 1; @(posedge clk); #1;
        c_rst = 0; @(posedge clk); #1;
        if (c_state !== S_FETCH) fail_msg("ctrl_hard_reset did not land in FETCH");
    end
endtask

task ctrl_wait_state(input [2:0] target, input integer max_cycles, output integer taken);
    integer c;
    begin
        c = 0;
        while ((c_state !== target) && (c < max_cycles)) begin
            @(posedge clk); #1;
            c = c + 1;
        end
        taken = c;
    end
endtask

// Drives one encoding to its terminal state, checking both where EXECUTE
// hands off to and whether rd is written there.
task check_encoding(input [31:0] instr);
    reg [2:0] cls, exp_state, got_state;
    reg       exp_regwrite;
    integer   c;
    begin
        cls = ref_class(instr);
        case (cls)
            C_LOAD:   begin exp_state = S_MEMORY;    exp_regwrite = 1'b1; end
            C_STORE:  begin exp_state = S_MEMORY;    exp_regwrite = 1'b0; end
            C_BRANCH: begin exp_state = S_FETCH;     exp_regwrite = 1'b0; end
            C_WRITES: begin exp_state = S_WRITEBACK; exp_regwrite = 1'b1; end
            default:  begin exp_state = S_WRITEBACK; exp_regwrite = 1'b0; end
        endcase

        ctrl_hard_reset;
        c_ir = instr;
        c_bt = 1'b0;

        ctrl_wait_state(S_EXECUTE, 5, c);
        if (c != 2) begin
            note_fail("control timing FETCH->EXECUTE");
            if (fail_budget >= 0)
                $display("        took %0d cycles (expected 2) for ir=%h", c, instr);
        end

        @(posedge clk); #1;
        got_state = c_state;
        if (got_state === exp_state) pass = pass + 1;
        else begin
            note_fail("control class -> terminal state");
            if (fail_budget >= 0)
                $display("        ir=%h cls=%0d expected state %0d after EXECUTE, got %0d",
                         instr, cls, exp_state, got_state);
        end

        if (cls == C_LOAD) begin
            @(posedge clk); #1;
            if (c_state !== S_WRITEBACK) begin
                note_fail("load must reach WRITEBACK");
                if (fail_budget >= 0) $display("        ir=%h got state %0d", instr, c_state);
            end
        end

        if (cls == C_STORE || cls == C_BRANCH) begin
            // Neither class has a WRITEBACK state at all.
            if (c_regwrite === 1'b0) pass = pass + 1;
            else begin
                note_fail("store/branch must never assert reg_write");
                if (fail_budget >= 0) $display("        ir=%h", instr);
            end
        end else begin
            if (c_regwrite === exp_regwrite) pass = pass + 1;
            else begin
                note_fail("reg_write in WRITEBACK");
                if (fail_budget >= 0)
                    $display("        ir=%h cls=%0d got=%b expected=%b", instr, cls, c_regwrite, exp_regwrite);
            end
        end
    end
endtask

task check_exec_signals(
    input [31:0]   encoding,
    input          bt,
    input          exp_a_sel,
    input          exp_b_sel,
    input [3:0]    exp_alu_op,
    input [2:0]    exp_wb_src,
    input          exp_pc_src,
    input          exp_store,
    input [8*40-1:0] name
);
    integer c;
    begin
        ctrl_hard_reset;
        c_ir = encoding;
        c_bt = bt;
        ctrl_wait_state(S_EXECUTE, 5, c);
        if (c_asel !== exp_a_sel || c_bsel !== exp_b_sel || c_aluop !== exp_alu_op ||
            c_wbsel !== exp_wb_src || c_pcsel !== exp_pc_src || c_store !== exp_store) begin
            note_fail(name);
            if (fail_budget >= 0)
                $display("        a=%b(%b) b=%b(%b) op=%h(%h) wb=%b(%b) pc=%b(%b) store=%b(%b)",
                    c_asel, exp_a_sel, c_bsel, exp_b_sel, c_aluop, exp_alu_op,
                    c_wbsel, exp_wb_src, c_pcsel, exp_pc_src, c_store, exp_store);
        end else pass = pass + 1;
    end
endtask

task suite_ctrl_sweep;
    reg [6:0] opcodes [0:10];
    reg [6:0] watch_f7 [0:7];
    integer oi, wi, f3i, f7i;
    begin
        opcodes[0]=OP_ALU_REG; opcodes[1]=OP_ALU_IMM; opcodes[2]=OP_LOAD;
        opcodes[3]=OP_STORE;   opcodes[4]=OP_BRANCH;  opcodes[5]=OP_JAL;
        opcodes[6]=OP_JALR;    opcodes[7]=OP_LUI;     opcodes[8]=OP_AUIPC;
        opcodes[9]=OP_SYSTEM;  opcodes[10]=OP_FENCE;
        // Valid boundaries plus clearly-invalid funct7 values.
        watch_f7[0]=7'b0000000; watch_f7[1]=7'b0100000; watch_f7[2]=7'b0000001;
        watch_f7[3]=7'b1000000; watch_f7[4]=7'b0010101; watch_f7[5]=7'b1111111;
        watch_f7[6]=7'b0000011; watch_f7[7]=7'b1010101;

        for (oi = 0; oi < 11; oi = oi + 1)
            for (f3i = 0; f3i < 8; f3i = f3i + 1)
                for (wi = 0; wi < 8; wi = wi + 1) begin
                    f7i = watch_f7[wi];
                    // rd=1 so a spurious reg_write is observable rather than
                    // masked by the x0 write-guard.
                    check_encoding({f7i[6:0], 5'd0, 5'd0, f3i[2:0], 5'd1, opcodes[oi]});
                end
        $display("  [S1.1] Control decode sweep: %0d encodings through the real FSM", 11*8*8);
    end
endtask

task suite_ctrl_fsm;
    integer c;
    begin
        c_rst = 1; c_ir = 32'h0000_0013; @(posedge clk); #1;
        if (c_state === S_RESET) pass=pass+1; else fail_msg("not in RESET while rst=1");

        c_rst = 0; @(posedge clk); #1;
        if (c_state === S_FETCH) pass=pass+1; else fail_msg("RESET->FETCH on rst deassert");

        ctrl_wait_state(S_EXECUTE, 5, c);
        if (c == 2) pass=pass+1; else fail_msg("FETCH->EXECUTE must take exactly 2 cycles");

        // Branch, taken: 3-cycle instruction, EXECUTE returns straight to FETCH.
        ctrl_hard_reset;
        c_ir = {7'b0, 5'd2, 5'd1, 3'b000, 5'b0, OP_BRANCH};
        c_bt = 1;
        ctrl_wait_state(S_EXECUTE, 5, c);
        if (c == 2) pass=pass+1; else fail_msg("branch FETCH->EXECUTE cycles");
        @(posedge clk); #1;
        if (c_state === S_FETCH) pass=pass+1; else fail_msg("EXECUTE(branch taken)->FETCH");

        // Store: 4-cycle, EXECUTE->MEMORY->FETCH, we_o only in MEMORY.
        ctrl_hard_reset;
        c_ir = {7'b0, 5'd2, 5'd1, 3'b010, 5'd0, OP_STORE};
        c_bt = 0;
        ctrl_wait_state(S_EXECUTE, 5, c);
        @(posedge clk); #1;
        if (c_state === S_MEMORY) pass=pass+1; else fail_msg("EXECUTE(store)->MEMORY");
        if (c_we === 1'b1) pass=pass+1; else fail_msg("we_o not asserted in MEMORY for store");
        @(posedge clk); #1;
        if (c_state === S_FETCH) pass=pass+1; else fail_msg("MEMORY(store)->FETCH");

        // Load: 5-cycle, EXECUTE->MEMORY->WRITEBACK->FETCH. oe_o must still be
        // asserted in WRITEBACK - that is what makes a load from the
        // combinational IMEM work at all.
        ctrl_hard_reset;
        c_ir = {12'd0, 5'd2, 3'b010, 5'd1, OP_LOAD};
        ctrl_wait_state(S_EXECUTE, 5, c);
        @(posedge clk); #1;
        if (c_state === S_MEMORY) pass=pass+1; else fail_msg("EXECUTE(load)->MEMORY");
        @(posedge clk); #1;
        if (c_state === S_WRITEBACK) pass=pass+1; else fail_msg("MEMORY(load)->WRITEBACK");
        if (c_oe === 1'b1) pass=pass+1;
        else fail_msg("oe_o must stay asserted in WRITEBACK for a load");
        @(posedge clk); #1;
        if (c_state === S_FETCH) pass=pass+1; else fail_msg("WRITEBACK(load)->FETCH");

        // sys_event_o: a one-cycle pulse in EXECUTE, for ECALL and EBREAK only.
        ctrl_hard_reset;
        c_ir = 32'h0000_0073; // ECALL
        ctrl_wait_state(S_EXECUTE, 5, c);
        if (c_sysevent === 1'b1) pass=pass+1; else fail_msg("sys_event_o not pulsed for ECALL");
        @(posedge clk); #1;
        if (c_state === S_WRITEBACK) pass=pass+1; else fail_msg("EXECUTE(ecall)->WRITEBACK");
        if (c_sysevent === 1'b0) pass=pass+1; else fail_msg("sys_event_o must not persist into WRITEBACK");
        if (c_regwrite === 1'b0) pass=pass+1; else fail_msg("ECALL must not assert reg_write");

        ctrl_hard_reset;
        c_ir = 32'h0010_0073; // EBREAK
        ctrl_wait_state(S_EXECUTE, 5, c);
        if (c_sysevent === 1'b1) pass=pass+1; else fail_msg("sys_event_o not pulsed for EBREAK");

        // A SYSTEM word that is not exactly ECALL or EBREAK must not pulse the
        // event, so stray ROM padding cannot forge a firmware-completion marker.
        ctrl_hard_reset;
        c_ir = 32'h0000_00F3; // SYSTEM, funct3=000, imm=0, but rd=1
        ctrl_wait_state(S_EXECUTE, 5, c);
        if (c_sysevent === 1'b0) pass=pass+1; else fail_msg("non-canonical SYSTEM word pulsed sys_event_o");
        @(posedge clk); #1;
        if (c_regwrite === 1'b0) pass=pass+1; else fail_msg("non-canonical SYSTEM word asserted reg_write");

        // Reset mid-instruction must abort we_o in the SAME cycle, not the next.
        ctrl_hard_reset;
        c_ir = {7'b0, 5'd2, 5'd1, 3'b010, 5'd0, OP_STORE};
        ctrl_wait_state(S_EXECUTE, 5, c);
        @(posedge clk); #1;
        if (c_we === 1'b1) pass=pass+1; else fail_msg("we_o should be asserted in MEMORY (pre-check)");
        c_rst = 1; #1;   // assert reset with no further clock edge
        if (c_we === 1'b0) pass=pass+1;
        else fail_msg("we_o must drop the same cycle rst_i asserts, mid-instruction");
        c_rst = 0;

        // Illegal instruction: reaches WRITEBACK, never MEMORY, writes nothing.
        ctrl_hard_reset;
        c_ir = 32'hFFFF_FFFF;
        ctrl_wait_state(S_EXECUTE, 5, c);
        @(posedge clk); #1;
        if (c_state === S_WRITEBACK) pass=pass+1; else fail_msg("illegal instruction must reach WRITEBACK");
        if (c_regwrite === 1'b0) pass=pass+1; else fail_msg("illegal instruction must not assert reg_write");
        if (c_we === 1'b0 && c_oe === 1'b0) pass=pass+1;
        else fail_msg("illegal instruction must not assert we_o/oe_o in WRITEBACK");
        $display("  [S1.2] Control FSM: transitions, cycle counts, sys_event, reset abort");
    end
endtask

task suite_ctrl_signals;
    begin
        // R-type: a=rs1(0), b=rs2(0), wb=ALU(000), pc=+4(0)
        check_exec_signals({7'b0000000, 5'd0, 5'd0, 3'b000, 5'd0, OP_ALU_REG}, 0, 0,0,4'h1,3'b000,0,0, "ADD selects");
        check_exec_signals({7'b0100000, 5'd0, 5'd0, 3'b000, 5'd0, OP_ALU_REG}, 0, 0,0,4'h2,3'b000,0,0, "SUB selects");
        check_exec_signals({7'b0000000, 5'd0, 5'd0, 3'b001, 5'd0, OP_ALU_REG}, 0, 0,0,4'h6,3'b000,0,0, "SLL selects");
        check_exec_signals({7'b0000000, 5'd0, 5'd0, 3'b010, 5'd0, OP_ALU_REG}, 0, 0,0,4'h9,3'b000,0,0, "SLT selects");
