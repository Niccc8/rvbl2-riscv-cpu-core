task suite_dmem;
    begin
        m_we=0; m_oe=0; m_bw=0; m_addr=0; m_wd=0;
        for (i = 0; i < MWORDS; i = i + 1) U_DMEM.mem[i] = 32'b0;
        @(posedge clk); #1;

        dmem_write(32'h1001_0000, 32'hCAFE_BABE, 4'b1111);
        dmem_read(32'h1001_0000);
        check_dmem(32'hCAFE_BABE, "full-word write then registered read-back");

        dmem_write(32'h1001_0000, 32'h00AA_0000, 4'b0100);
        dmem_read(32'h1001_0000);
        check_dmem(32'hCAAA_BABE, "single byte lane preserves the other three");

        dmem_write(32'h1001_0004, 32'h1111_2222, 4'b1111);
        repeat (5) @(posedge clk);
        dmem_read(32'h1001_0004);
        check_dmem(32'h1111_2222, "write survives idle cycles (true storage)");

        dmem_write(32'h1001_0008, 32'hFFFF_FFFF, 4'b1111);
        dmem_write(32'h1001_0008, 32'h0000_00AA, 4'b0001);
        dmem_read(32'h1001_0008); check_dmem(32'hFFFF_FFAA, "lane 0 only");
        dmem_write(32'h1001_0008, 32'h0000_BB00, 4'b0010);
        dmem_read(32'h1001_0008); check_dmem(32'hFFFF_BBAA, "lane 1 only");
        dmem_write(32'h1001_0008, 32'h00CC_0000, 4'b0100);
        dmem_read(32'h1001_0008); check_dmem(32'hFFCC_BBAA, "lane 2 only");
        dmem_write(32'h1001_0008, 32'hDD00_0000, 4'b1000);
        dmem_read(32'h1001_0008); check_dmem(32'hDDCC_BBAA, "lane 3 only");

        // Simultaneous we/oe cannot occur given the FSM's scoping, but if it
        // ever did the behaviour must be deterministic write-wins.
        @(posedge clk); #1;
        m_addr = 32'h1001_000C; m_wd = 32'h5555_5555; m_bw = 4'b1111; m_we = 1; m_oe = 1;
        @(posedge clk); #1; m_we = 0; m_oe = 0;
        dmem_read(32'h1001_000C);
        check_dmem(32'h5555_5555, "simultaneous we and oe -> write wins");

        dmem_write(32'h1001_0010, 32'hAAAA_BBBB, 4'b1111);
        dmem_write(32'h1001_0014, 32'hCCCC_DDDD, 4'b1111);
        dmem_read(32'h1001_0010); check_dmem(32'hAAAA_BBBB, "non-adjacent word A independent");
        dmem_read(32'h1001_0014); check_dmem(32'hCCCC_DDDD, "non-adjacent word B independent");

        dmem_read(32'h1001_0020);
        check_dmem(32'h0000_0000, "never-written word reads 0");

        dmem_write(32'h1001_0018, 32'hFFFF_FFFF, 4'b1111);
        dmem_write(32'h1001_0018, 32'h0000_5678, 4'b0011);
        dmem_read(32'h1001_0018); check_dmem(32'hFFFF_5678, "half-word write lanes 0+1");

        dmem_write(32'h1001_001C, 32'h0000_0000, 4'b1111);
        dmem_write(32'h1001_001C, 32'h9ABC_0000, 4'b1100);
        dmem_read(32'h1001_001C); check_dmem(32'h9ABC_0000, "half-word write lanes 2+3");

        dmem_write(32'h1001_0000 + (MWORDS-1)*4, 32'hDEAD_BEEF, 4'b1111);
        dmem_read(32'h1001_0000 + (MWORDS-1)*4);
        check_dmem(32'hDEAD_BEEF, "last implemented word");

        // Inside the architectural 8kB window but past the instantiated array:
        // must read 0 and write nothing, never alias into a real word. This is
        // the guard that makes DMEM_WORDS a safe resize knob.
        dmem_write(32'h1001_0000, 32'hA5A5_A5A5, 4'b1111);
        dmem_write(32'h1001_0080, 32'hDEAD_BEEF, 4'b1111);
        dmem_read(32'h1001_0000);
        check_dmem(32'hA5A5_A5A5, "out-of-range write must not alias into word 0");
        dmem_read(32'h1001_0080);
        check_dmem(32'h0000_0000, "out-of-range read returns 0, not an aliased word");
        dmem_read(32'h1001_1FFC);
        check_dmem(32'h0000_0000, "read at top of window, past array -> 0");
        $display("  [S0.10] DMEM: byte lanes, storage, aliasing prevention");
    end
endtask

