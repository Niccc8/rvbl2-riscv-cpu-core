// ===========================================================================
//  SUITE 0.3 - immediate generator (replaces the golden vector file)
// ===========================================================================
task suite_imm;
    begin
        f0 = 0;

        // Directed: sign-extension boundaries in every format.
        u_ins = {12'h800, 5'd0, 3'b000, 5'd0, OP_ALU_IMM}; #1;   // I-type, most negative
        if (u_immq !== 32'hFFFF_F800) begin f0=f0+1; note_fail("IMM I-type most negative"); end
        u_ins = {12'h7FF, 5'd0, 3'b000, 5'd0, OP_ALU_IMM}; #1;   // I-type, most positive
        if (u_immq !== 32'h0000_07FF) begin f0=f0+1; note_fail("IMM I-type most positive"); end
        u_ins = {20'hFFFFF, 5'd0, OP_LUI}; #1;
        if (u_immq !== 32'hFFFF_F000) begin f0=f0+1; note_fail("IMM U-type all ones"); end
        u_ins = {20'h00000, 5'd0, OP_AUIPC}; #1;
        if (u_immq !== 32'h0000_0000) begin f0=f0+1; note_fail("IMM U-type zero"); end

        // R-type / SYSTEM / FENCE are don't-care but must be defined, not x.
        u_ins = 32'h0000_0033; #1;
        if (u_immq !== 32'b0) begin f0=f0+1; note_fail("IMM R-type must be defined 0"); end
        u_ins = 32'h0000_0073; #1;
        if (u_immq !== 32'b0) begin f0=f0+1; note_fail("IMM SYSTEM must be defined 0"); end
        u_ins = 32'h0FF0_000F; #1;
        if (u_immq !== 32'b0) begin f0=f0+1; note_fail("IMM FENCE must be defined 0"); end

        // Randomised across every format. The bit-scrambling in the B and J
        // encodings is exactly the kind of thing a hand-written vector set
        // under-samples, so this sweeps far wider than the 33 golden vectors
        // the file-driven suite used.
        for (n = 0; n < 2000; n = n + 1) begin
            u_ins = $random;
            case (n % 8)
                0: u_ins[6:0] = OP_LUI;
                1: u_ins[6:0] = OP_AUIPC;
                2: u_ins[6:0] = OP_JAL;
                3: u_ins[6:0] = OP_BRANCH;
                4: u_ins[6:0] = OP_STORE;
                5: u_ins[6:0] = OP_ALU_IMM;
                6: u_ins[6:0] = OP_LOAD;
                7: u_ins[6:0] = OP_JALR;
            endcase
            #1;
            if (u_immq === ref_imm(u_ins)) pass = pass + 1;
            else begin
                f0 = f0 + 1;
                note_fail("IMM randomised");
                if (fail_budget >= 0)
                    $display("        ir=%h -> got=%h exp=%h", u_ins, u_immq, ref_imm(u_ins));
            end
        end

        if (f0 == 0) pass_msg("S0.3 Immediate generator: I/S/B/U/J formats, 2000 randomised");
        $display("  [S0.3] Immediate generator: directed boundaries + 2000 randomised");
    end
endtask

// ===========================================================================
//  SUITE 0.4 - multiplier
//  The expected value comes from a 64-bit software model, deliberately not
//  from the block's own a_signed/b_signed/sel_upper expressions.
// ===========================================================================
reg signed [63:0] mm_as, mm_bs;
reg        [63:0] mm_au, mm_bu, mm_ss, mm_uu, mm_su;
reg        [31:0] mm_exp;

task mult_expected(input [31:0] r1, input [31:0] r2, input [2:0] fn3);
    begin
        mm_as = $signed(r1); mm_bs = $signed(r2);
        mm_au = {32'b0, r1}; mm_bu = {32'b0, r2};
        mm_ss = mm_as * mm_bs;
        mm_uu = mm_au * mm_bu;
        mm_su = mm_as * mm_bu;
        case (fn3)
            3'b000:  mm_exp = mm_ss[31:0];
            3'b001:  mm_exp = mm_ss[63:32];
            3'b010:  mm_exp = mm_su[63:32];
            3'b011:  mm_exp = mm_uu[63:32];
            default: mm_exp = 32'b0;
        endcase
    end
endtask

task check_mult(input [8*64-1:0] name);
