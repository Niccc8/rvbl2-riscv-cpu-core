// ---------------------------------------------------------------------------
// SUITE 2A support
// ---------------------------------------------------------------------------
// Every failing subtest in the official firmware branches to the same _error
// label, so "x4 = FFFFFFFF" on its own says nothing about which one failed.
// This records the PC the jump into _error came from, which identifies the
// failing subtest exactly.
reg [31:0] fw_prev_pc, fw_err_from;
reg        fw_err_seen;

always @(posedge clk) begin
    if (rst === 1'b1) begin
        fw_prev_pc  <= 32'hFFFF_FFFF;
        fw_err_from <= 32'h0;
        fw_err_seen <= 1'b0;
    end else begin
        if (`PC.pc === FW_ERROR_PC && fw_prev_pc !== FW_ERROR_PC && !fw_err_seen) begin
            fw_err_from <= fw_prev_pc;
            fw_err_seen <= 1'b1;
        end
        fw_prev_pc <= `PC.pc;
    end
end

