#!/usr/bin/env python3
"""Put the official GPIO/UART test firmware into our instruction memory.

The organisers' README says: copy the lines of firmware.txt into the `case`
statement of the IMEM. This script does exactly that and nothing else. It
wraps the lines, unchanged, in our `imem` block (same ports as the one on the
ChipInventor canvas), and writes imem_official.v.

    python gen_imem.py            write imem_official.v
    python gen_imem.py --check    fail if imem_official.v is stale
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "firmware", "firmware.txt")
OUT = os.path.join(HERE, "imem_official.v")

HEAD = """// ============================================================================
// imem_official.v - the instruction memory with the OFFICIAL Stage 3 GPIO and
// UART test firmware in it.
//
// GENERATED by official-firmware-testbench/gen_imem.py from
// firmware/firmware.txt (organisers' file, unchanged); do not edit.
//
// As the organisers' README says: the lines of firmware.txt are copied
// verbatim into the `case` statement. Ports are the same as the imem block on
// the ChipInventor canvas, so this file replaces that block's Code with no
// wire change. The ROM is combinational and read only while oe_i is high.
// ============================================================================
module imem (
    input  wire [31:0] address_i,   // byte address from the address decoder
    input  wire        oe_i,        // read enable
    output reg  [31:0] data_o       // instruction
);
    wire [31:0] i_Address = {address_i[31:2], 2'b00};   // word-aligned address
    reg  [31:0] r_Instruction;

    always @(*) begin
        case (i_Address)
"""

TAIL = """
            default: r_Instruction = 32'h00000000;
        endcase
    end

    always @(*) data_o = oe_i ? r_Instruction : 32'h00000000;
endmodule
"""


def render():
    lines = [l.strip() for l in open(SRC, encoding="ascii").read().splitlines() if l.strip()]
    pat = re.compile(r"^32'h[0-9A-F]{8}: r_Instruction = 32'h[0-9A-F]{8};$")
    bad = [l for l in lines if not pat.match(l)]
    if bad:
        sys.exit("firmware.txt: unexpected line %r" % bad[0])
    return HEAD + "".join("            %s\n" % l for l in lines) + TAIL, len(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text, n = render()
    if a.check:
        cur = open(OUT, encoding="ascii").read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("FAIL imem_official.v is stale: run python gen_imem.py")
        print("OK   imem_official.v holds the %d instructions of firmware.txt" % n)
        return 0
    with open(OUT, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)
    print("wrote imem_official.v (%d instructions)" % n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
